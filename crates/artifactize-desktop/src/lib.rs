//! The artifactize desktop app: `monitor` and `review` as one Tauri window.
//!
//! The Rust side owns no state of its own beyond UI snapshots: it reads through the same
//! [`artifactize::monitor::Loader`] as the terminal monitor and acts through the same
//! [`artifactize::review::Job`]s as the terminal review. Commands and events are typed with
//! tauri-specta; [`bindings`] is the single list of what the frontend may call.

mod browse;
mod detail;
mod failure;
mod generation;
mod human;
mod launch;
mod status;
mod transcript;
mod watch;

pub use failure::Failure;
pub use launch::{Launch, Mode};

use specta_typescript::Typescript;
use std::path::Path;
use tauri::Manager;
use tauri_specta::{Builder, collect_commands, collect_events};

/// Where the generated TypeScript bindings live, relative to this crate.
pub const BINDINGS: &str = "ui/src/ipc/bindings.ts";

/// Every command and event the frontend can use, with their TypeScript types.
pub fn bindings<R: tauri::Runtime>() -> Builder<R> {
    Builder::new()
        .commands(collect_commands![
            launch::launch,
            browse::browse,
            browse::redraw,
            browse::toggle_worktrees,
            detail::detail,
            human::human_open,
            human::human_form,
            human::human_json,
            human::human_claim,
            human::human_run,
            human::human_cancel,
            human::human_submit,
            human::human_release,
            human::human_waiting,
            human::human_taken,
            transcript::transcript_open,
            transcript::transcript_window,
            transcript::transcript_close,
        ])
        .events(collect_events![watch::StateChanged, watch::SessionChanged])
}

/// Write the TypeScript bindings to `path`.
pub fn export(path: &Path) -> Result<(), String> {
    bindings::<tauri::Wry>()
        .export(
            Typescript::default().header("// Generated by artifactize-desktop; do not edit.\n"),
            path,
        )
        .map_err(|error| error.to_string())
}

/// The shared state behind every command, one per app.
pub struct App {
    pub launch: Launch,
    browse: browse::Browse,
    human: human::Reviews,
    transcripts: transcript::Transcripts,
    generation: generation::Generation,
}

impl App {
    pub fn new(launch: Launch) -> Self {
        Self {
            browse: browse::Browse::new(launch.initial()),
            launch,
            human: human::Reviews::default(),
            transcripts: transcript::Transcripts::default(),
            generation: generation::Generation::default(),
        }
    }

    /// Note the state origin a read found and return the state's generation. A replaced state
    /// (the monitor's [`Origin::replaces`]) drops the Human caches, claims taken here and running
    /// jobs of the old one.
    ///
    /// [`Origin::replaces`]: artifactize::monitor::Origin::replaces
    fn observe(&self, origin: artifactize::monitor::Origin) -> u32 {
        let (generation, replaced) = self.generation.observe(origin);
        if replaced {
            self.human.reset();
        }
        generation
    }
}

/// Build the Tauri app around `launch` on `builder`'s runtime; the caller runs it.
pub fn app<R: tauri::Runtime>(builder: tauri::Builder<R>, launch: Launch) -> tauri::Builder<R> {
    let specta = bindings::<R>();
    let state = launch.state.clone();
    builder
        .manage(App::new(launch))
        .invoke_handler(specta.invoke_handler())
        .setup(move |app| {
            specta.mount_events(app);
            watch::spawn(app.handle().clone(), state);
            Ok(())
        })
        .on_window_event(|window, event| {
            // A closing window cancels running Human tools, as quitting the terminal UI does.
            if let tauri::WindowEvent::Destroyed = event {
                window.state::<App>().human.cancel_all();
            }
        })
}
